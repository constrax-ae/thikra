/** Put a flat pack ("a.b": "text", "list[2]": "text") over a copy of English (the web's overlay). */
function overlay<T>(base: T, flat: Record<string, string>): T {
  const out: any = JSON.parse(JSON.stringify(base));
  for (const [path, text] of Object.entries(flat)) {
    if (typeof text !== 'string' || !text) continue;
    const parts = path.replace(/\[(\d+)\]/g, '.$1').split('.');
    let node = out;
    for (let i = 0; i < parts.length - 1 && node != null; i++) node = node[parts[i]];
    const last = parts[parts.length - 1];
    if (node != null && typeof node === 'object' && last in node && typeof node[last] === 'string') node[last] = text;
  }
  // A few phone keys carry a different name from the web's; take their text from the web's key.
  for (const [mine, web] of PACK_ALIASES) if (typeof flat[web] === 'string' && flat[web]) out[mine] = flat[web];
  return out;
}
/** [phone key, web key] for strings the phone stores under another name. */
const PACK_ALIASES: Array<[string, string]> = [
  ['pinTitle', 'twoStep'], ['pinOnShort', 'twoStepOn'], ['pinOffNote', 'twoStepOff'],
  ['loginPinTitle', 'pinTitle'], ['loginPinBody', 'pinBody'],
];

/** The web's rule: the saved choice, else the first device language we speak, else English. */
function pickLang(saved: string | null | undefined, device: readonly string[]): Lang {
  if (saved && (SUPPORTED as string[]).includes(saved)) return saved as Lang;
  for (const l of device) { let b = l.toLowerCase().split('-')[0]; if (b === 'fil') b = 'tl'; if ((SUPPORTED as string[]).includes(b)) return b as Lang; }
  return 'en';
}

/** The locale name for dates, times and numbers. */
export const intlLocale = (l: string) => (l === 'tl' ? 'fil' : l);

// Live bindings: screens read `t` and `lang` when they render, so after setLang() the app
// re-renders (App remounts on the change) and every screen shows the new language.
export let lang: Lang = 'en';
export let t: typeof ar = en;
export let isArabic = false;
export let isRtl = false;
export let machine = false;
export const locale = () => intlLocale(lang);

function apply(l: Lang) {
  lang = l;
  t = l === 'ar' ? ar : l === 'en' ? en : overlay(en, { ...PACKS[l](), ...PHONE_PACKS[l]() });
  isArabic = l === 'ar';
  isRtl = LANG_INFO[l].rtl;
  machine = LANG_INFO[l].machine;
}
apply(pickLang(null, [(globalThis as any).Intl?.DateTimeFormat?.().resolvedOptions?.().locale ?? 'en']));

const LANG_KEY = 'thekra.lang';
const langListeners = new Set<(l: Lang) => void>();

/**
 * Right-to-left languages mirror the whole layout, which React Native can only switch on a
 * reload. A development build reloads by itself; a release build asks to reopen the app
 * (an instant reload in production needs expo-updates, which is not installed yet).
 */
function ensureDirection() {
  // The web build has no DevSettings to reload with: there the page's own direction is enough.
  if (Platform.OS === 'web') { if (typeof document !== 'undefined') document.documentElement.dir = isRtl ? 'rtl' : 'ltr'; return; }
  if (I18nManager.isRTL === isRtl) return;
  I18nManager.allowRTL(isRtl);
  I18nManager.forceRTL(isRtl);
  if (__DEV__) setTimeout(() => DevSettings.reload(), 60);
  else Alert.alert(t.languageTitle, t.restartForDirection);
}

/** At start-up: the language this device chose before, if any. */
export async function loadLang() {
  try { const saved = await SecureStore.getItemAsync(LANG_KEY); if (saved) apply(pickLang(saved, [])); } catch { /* first run */ }
  langListeners.forEach(f => f(lang));
  ensureDirection();
}

/** Change the language now; remembered on this device. */
export async function setLang(l: Lang) {
  apply(l);
  try { await SecureStore.setItemAsync(LANG_KEY, l); } catch { /* it still holds for this run */ }
  langListeners.forEach(f => f(lang));
  ensureDirection();
}

/** Re-renders whatever uses it when the language changes. */
export function useLang(): Lang {
  const [l, setL] = useState(lang);
  useEffect(() => { const f = (x: Lang) => setL(x); langListeners.add(f); return () => { langListeners.delete(f); }; }, []);
  return l;
}

/** A chat notice stored as "sys:{k,a}" becomes words in the reader's language (the web's systemText). */
export function systemText(body: string): string {
  if (!body.startsWith('sys:')) return body;
  try {
    const { k, a } = JSON.parse(body.slice(4)) as { k: string; a: Record<string, string | number> };
    const tpl = t.sys[k];
    if (!tpl) return '';
    const vals: Record<string, string | number> = { ...a };
    if (a.n !== undefined && a.u) vals.wait = t.sys[a.u === 'h' ? 'waitH' : 'waitD'].replace('{n}', String(a.n));
    return tpl.replace(/\{(\w+)\}/g, (_, n) => String(vals[n] ?? ''));
  } catch { return ''; }
}
